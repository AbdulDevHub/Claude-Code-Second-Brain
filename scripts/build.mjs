#!/usr/bin/env node
// Scans a Claude Code home folder (default: ~/.claude) into a redacted knowledge graph and writes data.js.
//
//   node scripts/build.mjs                       your own brain -> ./data.js
//   node scripts/build.mjs --public              titles and descriptions only, no document contents
//   node scripts/build.mjs --home demo/ada --out demo/data.js
//   node scripts/build.mjs --redact my-handle    scrub extra words (also read from redact.local.txt)
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, basename, dirname, resolve } from 'node:path';
import { homedir } from 'node:os';
import { parseArgs } from 'node:util';
import { fileURLToPath } from 'node:url';
import { read, readJson, objectOr } from './lib/text.mjs';
import { createRedactor } from './lib/redact.mjs';
import { BrainGraph } from './lib/graph.mjs';
import { scanAll } from './lib/sources.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function build({ home = homedir(), omitBodies = false, extraRedactions = [] } = {}) {
  const started = performance.now();
  const claude = join(home, '.claude');
  if (!existsSync(claude)) throw new Error(`No Claude folder at ${claude}`);
  const userName = basename(home);
  const { redact, findLeak } = createRedactor(userName, extraRedactions);
  const graph = new BrainGraph({ redact, omitBodies });
  scanAll(graph, { home, claude, userName, settings: objectOr(readJson(join(claude, 'settings.json'))) });

  const nodes = [...graph.nodes.values()];
  const of = (type) => nodes.filter((n) => n.type === type);
  const tally = (type) => ({ total: of(type).length, active: of(type).filter((n) => n.active !== false).length });
  const stats = {
    memories: of('memory').length,
    notes: of('note').filter((n) => n.id !== 'note:index').length,
    skills: tally('skill'), mods: tally('mod'), mcp: tally('mcp'),
    agents: of('agent').length, projects: of('project').length,
    connections: graph.links.length, files: nodes.filter((n) => n.file).length,
    bytes: nodes.reduce((sum, n) => sum + n.size, 0),
    public: omitBodies, builtAt: Date.now(), buildMs: Math.round(performance.now() - started),
  };
  const json = JSON.stringify(graph.toJSON(stats));
  const leak = findLeak(json);
  if (leak) throw new Error(`Refusing to write: personal info survived redaction ("${leak}")`);
  return { json, stats, nodeCount: nodes.length };
}

function localRedactions() {
  const file = join(ROOT, 'redact.local.txt');
  return existsSync(file) ? read(file).split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#')) : [];
}

// ---------- CLI ----------
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { values } = parseArgs({
    options: {
      home: { type: 'string' },
      out: { type: 'string', default: join(ROOT, 'data.js') },
      public: { type: 'boolean', default: false },
      redact: { type: 'string', multiple: true, default: [] },
    },
  });
  try {
    const { json, stats, nodeCount } = build({
      home: values.home ? resolve(values.home) : homedir(),
      omitBodies: values.public,
      extraRedactions: [...values.redact, ...localRedactions()],
    });
    const out = resolve(values.out);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, `// Generated by scripts/build.mjs on ${new Date(stats.builtAt).toISOString()}. Do not edit.\nwindow.BRAIN = ${json};\n`);
    const pair = ({ active, total }) => `${active}/${total} active`;
    console.log(`Second Brain built in ${stats.buildMs}ms${stats.public ? ' (public: contents omitted)' : ''}`);
    console.log(`  ${nodeCount} nodes · ${stats.connections} connections`);
    console.log(`  ${stats.memories} memories · ${stats.notes} notes · ${stats.agents} agents`);
    console.log(`  skills ${pair(stats.skills)} · mods ${pair(stats.mods)} · mcp ${pair(stats.mcp)}`);
    console.log(`  -> ${out}`);
  } catch (err) {
    console.error(`Build failed: ${err.message}`);
    process.exit(1);
  }
}
